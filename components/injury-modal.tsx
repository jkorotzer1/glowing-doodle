"use client";

import { useCallback, useEffect, useRef, useState } from "react";

/**
 * Injury-report modal.
 *
 * The report is fetched on open rather than with the page: it costs an API
 * call per game, and the overwhelming majority of games are never clicked.
 */

export interface InjuryTarget {
  team: string;
  opponent: string;
  isHome: boolean;
  week: number;
  season: number;
}

interface ReportResponse {
  summary: string;
  sources: Array<{ title: string; url: string }>;
  model: string;
  generatedAt: string;
  cached: boolean;
  usage: {
    inputTokens: number;
    outputTokens: number;
    webSearches: number;
    tokenCostUsd: number;
  };
}

type Impact = "NONE" | "MINOR" | "MODERATE" | "MAJOR";

/** Severity colours run cool-to-hot so the eye finds MAJOR without reading. */
const IMPACT_STYLE: Record<Impact, string> = {
  NONE: "bg-slate-500/10 text-slate-400 ring-slate-500/25",
  MINOR: "bg-sky-500/10 text-sky-300 ring-sky-500/25",
  MODERATE: "bg-amber-500/10 text-amber-300 ring-amber-500/25",
  MAJOR: "bg-rose-500/10 text-rose-300 ring-rose-500/25",
};

interface Section {
  heading: string;
  impact: Impact | null;
  lines: string[];
}

/**
 * Split the model's prose into sections.
 *
 * The system prompt pins the format down, but this parse stays tolerant on
 * purpose: a drifted heading or a missing IMPACT line should cost the chip and
 * nothing else. Anything it cannot classify falls through as a plain line, so
 * no text is ever silently dropped from the modal.
 */
function parseSections(summary: string): Section[] {
  const sections: Section[] = [];
  let current: Section | null = null;

  for (const raw of summary.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;

    const heading = /^#{1,6}\s+(.*)$/.exec(line);
    if (heading) {
      current = { heading: heading[1]!.trim(), impact: null, lines: [] };
      sections.push(current);
      continue;
    }

    if (!current) {
      current = { heading: "", impact: null, lines: [] };
      sections.push(current);
    }

    const impact = /^IMPACT:\s*(NONE|MINOR|MODERATE|MAJOR)\b/i.exec(line);
    if (impact && current.impact === null) {
      current.impact = impact[1]!.toUpperCase() as Impact;
      continue;
    }

    current.lines.push(line.replace(/^[-*]\s+/, ""));
  }

  return sections;
}

/**
 * The warning that belongs next to anything an LLM wrote.
 *
 * Stated once, here, so every surface that opens the modal carries it: the
 * numbers in this app come from feeds we ingest and can audit, and this does
 * not. It is a search summary, and it can be wrong.
 */
export const INJURY_DISCLAIMER =
  "Generated by Claude from a live web search — not an ingested feed. Verify anything you act on.";

export function InjuryModal({
  target,
  onClose,
}: {
  target: InjuryTarget;
  onClose: () => void;
}) {
  const [report, setReport] = useState<ReportResponse | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const closeRef = useRef<HTMLButtonElement>(null);

  const away = target.isHome ? target.opponent : target.team;
  const home = target.isHome ? target.team : target.opponent;

  const load = useCallback(
    async (refresh: boolean, signal?: AbortSignal) => {
      setLoading(true);
      setError(null);
      try {
        const res = await fetch("/api/injuries", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            season: target.season,
            week: target.week,
            team: target.team,
            opponent: target.opponent,
            refresh,
          }),
          signal,
        });
        const data = await res.json();
        if (!res.ok) throw new Error(data.error ?? `Request failed (${res.status}).`);
        setReport(data as ReportResponse);
      } catch (err) {
        // An abort is the component unmounting, not a failure to show.
        if (err instanceof DOMException && err.name === "AbortError") return;
        setError(err instanceof Error ? err.message : "Injury lookup failed.");
      } finally {
        if (!signal?.aborted) setLoading(false);
      }
    },
    [target.season, target.week, target.team, target.opponent],
  );

  useEffect(() => {
    const controller = new AbortController();
    void load(false, controller.signal);
    return () => controller.abort();
  }, [load]);

  // Escape closes. Bound on the document so it works before the dialog has
  // taken focus -- which matters while the report is still loading.
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
    };
    document.addEventListener("keydown", onKey);
    return () => document.removeEventListener("keydown", onKey);
  }, [onClose]);

  useEffect(() => {
    closeRef.current?.focus();
  }, []);

  const sections = report ? parseSections(report.summary) : [];

  return (
    <div
      className="fixed inset-0 z-50 flex items-start justify-center overflow-y-auto bg-slate-950/80 p-4 backdrop-blur-sm sm:p-8"
      // A click that STARTS on the panel and ends on the backdrop (a drag while
      // selecting text) must not close the modal, so the handler checks that
      // the backdrop is itself the target rather than listening for any click.
      onMouseDown={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
      role="presentation"
    >
      <div
        role="dialog"
        aria-modal="true"
        aria-label={`Injury report, ${away} at ${home}`}
        className="my-auto w-full max-w-2xl rounded-lg border border-slate-800 bg-slate-900 shadow-2xl"
      >
        <header className="flex items-start justify-between gap-4 border-b border-slate-800 px-5 py-4">
          <div>
            <h2 className="text-sm font-semibold text-slate-100">
              {away} <span className="text-slate-500">@</span> {home}
            </h2>
            <p className="mt-0.5 text-xs text-slate-500">
              Week {target.week} · injury report
            </p>
          </div>
          <button
            ref={closeRef}
            type="button"
            onClick={onClose}
            aria-label="Close"
            className="rounded-sm px-2 py-1 text-lg leading-none text-slate-500 hover:bg-slate-800 hover:text-slate-200 focus:outline-none focus-visible:ring-1 focus-visible:ring-sky-500"
          >
            ×
          </button>
        </header>

        <div className="px-5 py-4">
          {loading && (
            <div className="flex items-center gap-3 py-6 text-sm text-slate-400">
              <span className="h-3 w-3 animate-spin rounded-full border-2 border-slate-600 border-t-sky-400" />
              Searching for the latest injury reports…
            </div>
          )}

          {!loading && error && (
            <div className="rounded-md border border-rose-900/60 bg-rose-950/30 px-3 py-3 text-sm text-rose-200">
              {error}
            </div>
          )}

          {!loading && !error && report && (
            <div className="space-y-5">
              {sections.map((section, i) => (
                <section key={i}>
                  {section.heading && (
                    <div className="flex items-center gap-2">
                      <h3 className="text-xs font-semibold uppercase tracking-wide text-slate-300">
                        {section.heading}
                      </h3>
                      {section.impact && (
                        <span
                          className={`rounded-sm px-1.5 py-0.5 text-[10px] font-semibold uppercase tracking-wide ring-1 ring-inset ${IMPACT_STYLE[section.impact]}`}
                        >
                          {section.impact}
                        </span>
                      )}
                    </div>
                  )}
                  <ul className="mt-2 space-y-1.5 text-sm leading-relaxed text-slate-300">
                    {section.lines.map((line, j) => (
                      <li key={j} className="flex gap-2">
                        <span aria-hidden="true" className="text-slate-600">
                          ·
                        </span>
                        <span>{line}</span>
                      </li>
                    ))}
                  </ul>
                </section>
              ))}
            </div>
          )}
        </div>

        {!loading && !error && report && (
          <footer className="space-y-3 border-t border-slate-800 px-5 py-3">
            {report.sources.length > 0 && (
              <div>
                <p className="text-[10px] uppercase tracking-wide text-slate-500">
                  Sources
                </p>
                <ul className="mt-1 space-y-0.5">
                  {report.sources.map((s) => (
                    <li key={s.url} className="truncate text-xs">
                      <a
                        href={s.url}
                        target="_blank"
                        rel="noreferrer"
                        className="text-sky-400 hover:underline"
                      >
                        {s.title}
                      </a>
                    </li>
                  ))}
                </ul>
              </div>
            )}
            <p className="text-[11px] leading-relaxed text-slate-500">
              {INJURY_DISCLAIMER}
            </p>
            <div className="flex items-center justify-between gap-3 text-[11px] text-slate-500">
              <span>
                {report.model}
                {report.cached && " · cached"} ·{" "}
                {new Date(report.generatedAt).toLocaleString()}
                {report.usage && (
                  <>
                    {" · "}
                    <span
                      title={
                        `${report.usage.inputTokens.toLocaleString()} input tokens, ` +
                        `${report.usage.outputTokens.toLocaleString()} output tokens, ` +
                        `${report.usage.webSearches} web searches.\n\n` +
                        "The dollar figure is TOKENS ONLY. Web search is billed " +
                        "per search on top of it, so the real cost of this call " +
                        "is higher. See the Console usage page for the billed total."
                      }
                    >
                      ${report.usage.tokenCostUsd.toFixed(3)} tokens +{" "}
                      {report.usage.webSearches} searches
                    </span>
                  </>
                )}
              </span>
              <button
                type="button"
                onClick={() => void load(true)}
                className="rounded-sm px-2 py-1 text-slate-400 hover:bg-slate-800 hover:text-slate-200 focus:outline-none focus-visible:ring-1 focus-visible:ring-sky-500"
              >
                Re-run search
              </button>
            </div>
          </footer>
        )}
      </div>
    </div>
  );
}

